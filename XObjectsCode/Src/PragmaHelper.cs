#nullable enable
using System;
using System.IO;
using System.Reflection;
using System.Text;

namespace Xml.Schema.Linq.CodeGen
{
    static class PragmaHelper
    {
        public static string GetLinqToXsdVersion()
        {
            var assembly = typeof(XObjectsCoreGenerator).Assembly;
            var infoVerAttr = assembly.GetCustomAttribute<AssemblyInformationalVersionAttribute>();
            if (infoVerAttr != null && !string.IsNullOrEmpty(infoVerAttr.InformationalVersion)) {
                return infoVerAttr.InformationalVersion.Split('+')[0];
            }

            var ver = assembly.GetName().Version;
            if (ver != null) {
                return ver.Build >= 0
                    ? $"{ver.Major}.{ver.Minor}.{ver.Build}"
                    : $"{ver.Major}.{ver.Minor}";
            }

            return "3.4.21";
        }

        public static void UpdateAutoGeneratedComment(this StringWriter writer, string? toolVersion = null)
        {
            if (writer == null) return;
            UpdateAutoGeneratedComment(writer.GetStringBuilder(), toolVersion);
        }

        public static void UpdateAutoGeneratedComment(this StringBuilder builder, string? toolVersion = null)
        {
            if (builder == null || builder.Length == 0) return;

            toolVersion ??= GetLinqToXsdVersion();
            string replacementLine = $"//     LinqToXsd Version: {toolVersion}";

            int runtimeVersionIndex = IndexOf(builder, "Runtime Version:");
            if (runtimeVersionIndex < 0) return;

            int lineStart = runtimeVersionIndex;
            while (lineStart > 0 && builder[lineStart - 1] != '\n' && builder[lineStart - 1] != '\r') {
                lineStart--;
            }

            int lineEnd = runtimeVersionIndex;
            while (lineEnd < builder.Length && builder[lineEnd] != '\r' && builder[lineEnd] != '\n') {
                lineEnd++;
            }

            builder.Remove(lineStart, lineEnd - lineStart);
            builder.Insert(lineStart, replacementLine);
        }

        public static void InsertFilePragma(this StringWriter writer, string pragma)
        {
            var builder = writer.GetStringBuilder();
            // Insert the pragma on the first blank line, which will be just after the <auto-generated> comment.            
            int blankIndex = IndexOfBlankLine(builder);
            builder.Insert(blankIndex, pragma + "\r\n");
        }

        private static int IndexOf(StringBuilder builder, string value)
        {
            if (builder.Length < value.Length) return -1;
            int maxSearchLength = Math.Min(builder.Length - value.Length, 4096);

            for (int i = 0; i <= maxSearchLength; i++) {
                bool match = true;
                for (int j = 0; j < value.Length; j++) {
                    if (builder[i + j] != value[j]) {
                        match = false;
                        break;
                    }
                }
                if (match) return i;
            }

            return -1;
        }

        private static int IndexOfBlankLine(StringBuilder builder)
        {
            // We look for two chars \n[\r\n], so the stop condition is one less than actual length
            for (int i = 0; i < builder.Length - 1; i++)
            {
                if (builder[i] == '\n')
                {
                    ++i;    // Safe because of the `Length - 1` stop condition
                    if (builder[i] == '\r' || builder[i] == '\n')
                    {
                        return i;
                    }
                }
            }
            return 0;
        }
    }
}